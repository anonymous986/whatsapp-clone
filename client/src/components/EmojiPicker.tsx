export const EmojiPicker: React.FC<EmojiPickerProps> = ({
  onEmojiSelect,
  onClose,
}) => {
  const [activeCategory, setActiveCategory] = useState('Smileys & Emotion')

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji)
  }

  const handleKeyDown = (e: React.KeyboardEvent) => {
    if (e.key === 'Escape') {
      onClose()
    }
  }

  return (
    <div className="bg-wa-dark-secondary rounded-lg shadow-lg border border-wa-dark-border p-3" onKeyDown={handleKeyDown}>
      {/* Category Tabs */}
      <div className="flex space-x-1 mb-3 overflow-x-auto">
        {Object.keys(EMOJI_CATEGORIES).map((category) => (
          <button
            key={category}
            onClick={() => setActiveCategory(category)}
            className={`px-2 py-1 text-xs rounded whitespace-nowrap transition-colors duration-200 ${
              activeCategory === category
                ? 'bg-wa-accent text-white'
                : 'text-wa-text-secondary hover:text-wa-text-primary hover:bg-wa-dark-tertiary'
            }`}
          >
            {category}
          </button>
        ))}
      </div>

      {/* Emoji Grid */}
      <div className="grid grid-cols-8 gap-1 max-h-60 overflow-y-auto">
        {EMOJI_CATEGORIES[activeCategory as keyof typeof EMOJI_CATEGORIES].map((emoji, index) => (
          <button
            key={`${emoji}-${index}`}
            onClick={() => handleEmojiClick(emoji)}
            className="flex items-center justify-center w-8 h-8 text-lg hover:bg-wa-dark-tertiary rounded transition-colors duration-200"
            title={emoji}
          >
            {emoji}
          </button>
        ))}
      </div>

      {/* Close Button */}
      <div className="flex justify-end mt-2">
        <button
          onClick={onClose}
          className="text-xs text-wa-text-tertiary hover:text-wa-text-primary transition-colors duration-200"
        >
          Close
        </button>
      </div>
    </div>
  )
}